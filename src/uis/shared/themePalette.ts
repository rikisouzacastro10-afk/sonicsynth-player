import type { UIId } from '../../types/music';

export interface ThemePaletteSpec {
  shell: (isDark: boolean) => string;
  card: (isDark: boolean) => string;
  cardHover: (isDark: boolean) => string;
  miniPlayer: (isDark: boolean) => string;
  lyricsCard: (isDark: boolean) => string;
  lyricsVariant: (isDark: boolean) => 'dark' | 'light' | 'crt' | 'stage' | 'stage-light';
  accentBg: string;
  accentText: (isDark: boolean) => string;
  progressFill: string;
  progressBg: (isDark: boolean) => string;
  radius: string;
  headingFont: string;
  labelTag: string;
  isRetro?: boolean;
  isKawaii?: boolean;
}

const makeModernPalette = (opts: {
  darkShell: string;
  lightShell: string;
  darkCard: string;
  lightCard: string;
  darkLyrics: string;
  lightLyrics: string;
  accentBg: string;
  accentTextDark: string;
  accentTextLight: string;
  progressFill: string;
  radius?: string;
  headingFont?: string;
  labelTag: string;
  isRetro?: boolean;
  isKawaii?: boolean;
}): ThemePaletteSpec => ({
  shell: (isDark) => (isDark ? opts.darkShell : opts.lightShell),
  card: (isDark) => (isDark ? opts.darkCard : opts.lightCard),
  cardHover: (isDark) =>
    isDark ? 'hover:bg-white/[0.08]' : 'hover:bg-black/[0.04]',
  miniPlayer: (isDark) =>
    `${isDark ? opts.darkCard : opts.lightCard} backdrop-blur-xl shadow-2xl`,
  lyricsCard: (isDark) => (isDark ? opts.darkLyrics : opts.lightLyrics),
  lyricsVariant: (isDark) => (isDark ? 'stage' : 'stage-light'),
  accentBg: opts.accentBg,
  accentText: (isDark) => (isDark ? opts.accentTextDark : opts.accentTextLight),
  progressFill: opts.progressFill,
  progressBg: (isDark) => (isDark ? 'bg-white/15' : 'bg-black/15'),
  radius: opts.radius || 'rounded-2xl',
  headingFont: opts.headingFont || 'font-display',
  labelTag: opts.labelTag,
  isRetro: opts.isRetro,
  isKawaii: opts.isKawaii,
});

